"""Data panels of the main figures redrawn from panel tables.

The same functions draw the frozen Source Data tables (quick line) and the tables regenerated by the checkpoint line
(Figs. 2-6 in both). Layout and styling are simplified; schematic and microscopy panels (Figs. 1,
2a, 4a top, 5b/d-f images, 6a) are not redrawn, and 4g is a curated summary drawn as text.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib

