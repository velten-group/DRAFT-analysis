COLOR = {"DRAFT": "#d62728", "SCENIC+": "#8c564b", "scDoRI": "#ff7f0e", "scMTNI": "#2ca02c", "Dictys": "#1f77b4",
         "Random": "#7f7f7f", "Ground truth": "#000000", "Shared GAT": "#9467bd", "LR+GRU": "#e377c2",
         "Shared LR": "#bcbd22", "CellChat": "#1f77b4", "LIANA+": "#17becf", "LR expression": "#bcbd22",
         "scMTNI+Prior": "#2ca02c", "SCENIC": "#8c564b"}
plt.rcParams.update({"font.size": 7, "axes.titlesize": 8, "axes.labelsize": 7, "legend.fontsize": 6,
                     "axes.spines.top": False, "axes.spines.right": False, "axes.linewidth": 0.6,
                     "pdf.fonttype": 42, "svg.fonttype": "none"})


class Tables:
    """Reads panel tables of one kind from a directory (source_data/<kind> or results/checkpoint/panels/<kind>)."""

    def __init__(self, folder: Path):
        self.folder = folder

    def __call__(self, name: str) -> pd.DataFrame:
        return source_data.read_table(self.folder / name)


def _c(method: str) -> str:
    return COLOR.get(method, "#555555")


def _heat(ax, df: pd.DataFrame, title: str, cmap="OrRd", rotate=90, vmax=None):
    m = df.to_numpy(float)
    im = ax.imshow(m, aspect="auto", cmap=cmap, vmin=0, vmax=vmax, interpolation="nearest")
    ax.set_xticks(range(df.shape[1]), df.columns, rotation=rotate, fontsize=5)
    ax.set_yticks(range(df.shape[0]), df.index, fontsize=5)
    ax.set_title(title)
    return im


def figure2(t: Tables) -> plt.Figure:
    fig, axes = plt.subplots(2, 3, figsize=(10, 6), layout="constrained")
    for ax, panel, title in ((axes[0, 0], "2b", "b  DRAFT and existing methods"),
                             (axes[1, 1], "2e", "e  internal ablations")):
        d = t(f"fig2_Fig_{panel}_0.tsv")
        for m, g in d.groupby("method", sort=False):
            ax.errorbar(g.stage, g.candidate_AUROC_mean, yerr=g.SD_across_datasets, label=m, color=_c(m), lw=1,
                        marker="o", ms=2.5, capsize=1.5)
        ax.set(xlabel="Stage", ylabel="Candidate AUROC", title=title)
        ax.legend(frameon=False)
    sens = t("fig2_Fig_2c-d_0.tsv")
    for ax, panel, ylab in ((axes[0, 1], "c", "Candidate AUROC"), (axes[0, 2], "d", "Temporal smoothness")):
        d = sens[sens.panel.eq(panel)]
        for m, g in d.groupby("method", sort=False):
            g = g.sort_values("prior_SNR")
            ax.errorbar(g.prior_SNR, g["mean"], yerr=g.SD_across_datasets.fillna(0), label=m, color=_c(m), lw=1,
                        marker="o", ms=2.5, capsize=1.5, ls="--" if m == "Ground truth" else "-")
        for r in t("fig2_Fig_2c-d_2.tsv").itertuples():
            ax.axvline(r.prior_SNR, color="0.6", lw=0.6, ls=":")
            ax.text(r.prior_SNR, ax.get_ylim()[1], r.reference.replace(" data prior", ""), fontsize=5, ha="center",
                    va="bottom")
        ax.set(xlabel="Prior SNR", ylabel=ylab, title=f"{panel}  sensitivity to prior structure")
        ax.legend(frameon=False)
    f = t("fig2_Fig_2f_0.tsv")
    ax = axes[1, 2]
    ax.bar(range(len(f)), f.temporal_smoothness_mean, yerr=f.SD_across_datasets.fillna(0),
           color=[_c(m) for m in f.method], capsize=1.5)
    ax.set_xticks(range(len(f)), f.method, rotation=45, ha="right")
    ax.set(ylabel="Temporal smoothness", title="f  temporal smoothness")
    axes[1, 0].axis("off")
    axes[1, 0].text(0, 0.5, "a  schematic (not redrawn)", fontsize=8, color="0.4")
    return fig


def figure3(t: Tables) -> plt.Figure:
    fig = plt.figure(figsize=(11, 7), layout="constrained")
    gs = fig.add_gridspec(2, 4)
    a = t("fig3_Fig_3a_0.tsv").set_index("cluster")
    samples = a.columns[2:]
    ax = fig.add_subplot(gs[0, 0])
    frac = a[samples].div(a[samples].sum(1), axis=0)
    bottom = np.zeros(len(frac))
    for s, col in zip(samples, plt.get_cmap("viridis")(np.linspace(0, 1, len(samples)))):
        ax.bar(frac.index, frac[s], bottom=bottom, label=s, color=col, width=0.8)
        bottom += frac[s].to_numpy()
    ax.set(ylabel="Fraction of cells", title="a  sample composition")
    ax.legend(frameon=False, fontsize=5, ncol=2)
    b = t("fig3_Fig_3b_0.tsv")
    for j, (metric, sd) in enumerate((("AUROC_mean", "AUROC_SD"), ("AUPR_mean", "AUPR_SD"))):
        ax = fig.add_subplot(gs[0, 1 + j])
        golds = list(dict.fromkeys(b.gold_standard))
        models = list(dict.fromkeys(b.model))
        for k, m in enumerate(models):
            g = b[b.model.eq(m)].set_index("gold_standard").loc[golds]
            x = np.arange(len(golds)) + (k - len(models) / 2) * 0.12
            ax.errorbar(x, g[metric], yerr=g[sd], fmt="o", ms=3, color=_c(m), label=m, capsize=1.5)
        ax.set_xticks(range(len(golds)), golds)
        ax.set(title=f"b  {metric.split('_')[0]} (mean ± SD over 7 clusters)")
        if j == 0:
            ax.legend(frameon=False)
    for k, (blk, name) in enumerate(((1, "DRAFT"), (3, "Dictys"), (5, "scMTNI+Prior"), (7, "SCENIC"))):
        if k == 0:
            ax = fig.add_subplot(gs[0, 3])
        else:
            ax = fig.add_subplot(gs[1, k - 1])
        _heat(ax, t(f"fig3_Fig_3c_{blk}.tsv").set_index("cluster"), f"c  {name}: normalized distance", cmap="YlOrRd",
              vmax=1)
    _heat(fig.add_subplot(gs[1, 3]), t("fig3_Fig_3d_0.tsv").set_index("edge_cluster"), "d  edge clusters", rotate=0)
    return fig


def figure4(t: Tables) -> plt.Figure:
    fig = plt.figure(figsize=(11, 8), layout="constrained")
    gs = fig.add_gridspec(3, 4)
    a = t("fig4_Fig_4a_0.tsv")
    ax = fig.add_subplot(gs[0, 0])
    ax.bar(a.cell_type, a.n_cells, color=a.lineage.map({"Germline": "#1f77b4", "Hub": "#d62728", "Somatic": "#2ca02c"}))
    ax.tick_params(axis="x", rotation=60)
    ax.set(ylabel="Cells", title="a  cells per cell type")
    b = t("fig4_Fig_4b_0.tsv")
    for j, assay in enumerate(("SpG", "SpC")):
        ax = fig.add_subplot(gs[0, 1 + j])
        d = b[b.assay.eq(assay)]
        methods = list(dict.fromkeys(d.method))
        ax.boxplot([d[d.method.eq(m)].AUROC for m in methods], tick_labels=methods, widths=0.6, showfliers=False)
        for i, m in enumerate(methods, 1):
            v = d[d.method.eq(m)].AUROC
            ax.scatter(np.full(len(v), i) + np.linspace(-0.12, 0.12, len(v)), v, s=6, color=_c(m), zorder=3)
        ax.axhline(0.5, color="0.6", lw=0.6, ls="--")
        ax.set(ylabel="AUROC (RE→TG)", title=f"b  {assay} Hi-C")
    smooth = t("fig4_Fig_4c_0.tsv")
    for j, (blk, lin) in enumerate(((1, "Germline"), (3, "Soma"))):
        ax = fig.add_subplot(gs[1, j])
        s = ", ".join(f"{r.smoothness:.3f}" for r in smooth[smooth.lineage.eq(lin)].itertuples())
        _heat(ax, t(f"fig4_Fig_4c_{blk}.tsv").set_index("stage"), f"c  {lin}: smoothness {s}", cmap="YlOrRd", vmax=1)
    d = t("fig4_Fig_4d_0.tsv")
    ax = fig.add_subplot(gs[0, 3])
    ax.barh(d.TG[::-1], d.mean_cos_sim[::-1], color=np.where(d.highlighted[::-1], "#d62728", "0.6"))
    ax.set(xlim=(d.mean_cos_sim.min() - 0.02, d.mean_cos_sim.max() + 0.005), xlabel="TF-TG cosine",
           title="d  ovo eRegulon (GSC, top 20)")
    ax.tick_params(axis="y", labelsize=5)
    _heat(fig.add_subplot(gs[1, 2:]), t("fig4_Fig_4e_0.tsv").set_index("edge_cluster"), "e  edge clusters x stages")
    _heat(fig.add_subplot(gs[2, :2]), t("fig4_Fig_4f_0.tsv").set_index("topic"), "f  topics x stages")
    ax = fig.add_subplot(gs[2, 2:])
    ax.axis("off")
    lines = [f"{r.node}: {r.edge_clusters} | {r.TFs}" for r in t("fig4_Fig_4g_0.tsv").itertuples()]
    lines += [f"{r.box} ({r.topics}): {r.listed_terms}" for r in t("fig4_Fig_4g_2.tsv").itertuples()]
    ax.text(0, 1, "g  trajectory summary\n" + "\n".join(lines), va="top", fontsize=6)
    return fig


def figure5(t: Tables) -> plt.Figure:
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4), layout="constrained")
    a = t("fig5_Fig_5a_0.tsv")
    ax = axes[0]
    x = a.stage_index
    mean = a["centrality_mean_of_5_seeds (line)"]
    scale = a["centrality_max (band)"].max()
    ax.fill_between(x, a["centrality_min (band)"] / scale, a["centrality_max (band)"] / scale, color="#d62728",
                    alpha=0.2, lw=0, label="range of 5 models")
    ax.plot(x, mean / scale, color="#d62728", lw=1.2, label="network centrality (mean)")
    ax.plot(x, a.mean_normalized_expression / a.mean_normalized_expression.max(), color="0.3", lw=1, ls="--",
            label="expression")
    ax.set_xticks(x, a.stage, rotation=90)
    ax.set(ylabel="Scaled to maximum = 1", title="a  Mondo: centrality in five models and expression")
    ax.legend(frameon=False)
    c = t("fig5_Fig_5c_0.tsv")
    ax = axes[1]
    ax.barh(c.TG[::-1], c.rrf_score[::-1], color=np.where(c.highlighted[::-1], "#d62728", "0.6"))
    ax.set(xlabel="Reciprocal-rank fusion score", title="c  Mondo eRegulon, GSC to Sp-4 (top 20)")
    ax.tick_params(axis="y", labelsize=5)
    return fig


