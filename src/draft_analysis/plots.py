FIGURES = {2: figure2, 3: figure3, 4: figure4, 5: figure5, 6: figure6}


def draw(line: str, figures=None) -> list[Path]:
    """line = "quick" (Source Data, results/quick/figures) or "checkpoint" (results/checkpoint/figures)."""
    quick = line == "quick"
    folder = paths.SOURCE_DATA / "main" if quick else paths.PANELS["main"]
    out = (paths.QUICK if quick else paths.CHECKPOINT) / "figures"
    out.mkdir(parents=True, exist_ok=True)
    t = Tables(folder)
    written = []
    for n in figures or FIGURES:
        fig = FIGURES[n](t)
        source = "the Source Data" if quick else ("the saved predictions" if n == 2 else "the checkpoints")
        fig.suptitle(f"Figure {n} (data panels, redrawn from {source})",
                     fontsize=9)
        for ext in ("png", "pdf"):
            p = out / f"Figure_{n}.{ext}"
            fig.savefig(p, dpi=600)
            written.append(p)
        plt.close(fig)
    return written
